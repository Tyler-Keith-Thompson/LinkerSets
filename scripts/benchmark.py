#!/usr/bin/env python3
"""Measures what records cost: the build time of a module of N @LinkerSetEntry records against the
same declarations without the macro, and the time to read N records, for N of 100, 1,000 and
10,000.

    just benchmark [--sizes 100,1000,10000] [--rounds 3] [--files 1]

It writes a SwiftPM package under .build/benchmark that depends on this checkout, one target per
size and kind (records, or the macro-free control, each generated by tools/many_records), and an
executable that reads each set in release. Dependencies (swift-syntax, LinkerSets, the plugin) are
built first, so each timed build compiles only its own target. Prints a Markdown table.
"""

import argparse
import os
import shutil
import statistics
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATOR = os.path.join(ROOT, 'tools', 'many_records', 'many_records.sh')
KIND = '0x6265_6E63'  # "benc"
# SwiftPM names a package on disk by its directory.
PACKAGE = os.path.basename(ROOT).lower()


def swift(*arguments, cwd):
    """Runs `swift` with Xcode's default toolchain, failing loudly with its output."""
    environment = dict(os.environ)
    environment.pop('TOOLCHAINS', None)
    command = ['xcrun', '--toolchain', 'default', 'swift', *arguments] if sys.platform == 'darwin' else ['swift', *arguments]
    result = subprocess.run(command, cwd=cwd, env=environment, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f'{" ".join(command)} failed:\n{result.stdout}\n{result.stderr}')
    return result.stdout


def write_sources(directory, count, kind, files):
    """`count` declarations split evenly across `files` sources, each an enum of its own."""
    spec = os.path.join(directory, 'records.spec')
    with open(spec, 'w') as file:
        file.write(f'{count} {kind}\n')
    outputs = [os.path.join(directory, f'Generated{index}.swift') for index in range(files)]
    subprocess.run(['sh', GENERATOR, *outputs, '--', spec], check=True)
    os.remove(spec)


def write_package(directory, sizes, files):
    targets = []
    for size in sizes:
        for name, kind in [(f'Records{size}', KIND), (f'Unrecorded{size}', 'none')]:
            os.makedirs(os.path.join(directory, 'Sources', name), exist_ok=True)
            write_sources(os.path.join(directory, 'Sources', name), size, kind, files)
            dependencies = f'[.product(name: "LinkerSets", package: "{PACKAGE}")]' if kind != 'none' else '[]'
            targets.append(f'        .target(name: "{name}", dependencies: {dependencies}, path: "Sources/{name}"),')
    os.makedirs(os.path.join(directory, 'Sources', 'Read'), exist_ok=True)
    # The records target is linked, unnamed in the source: SwiftPM links every dependency's
    # objects, so its records are in the binary without an import.
    with open(os.path.join(directory, 'Sources', 'Read', 'main.swift'), 'w') as file:
        file.write(f'''import LinkerSets

let clock = ContinuousClock()
var fastest = Duration.seconds(1_000)
var found = 0
for _ in 0..<50 {{
    let elapsed = clock.measure {{ found = LinkerSet<Int>(kind: LinkerSetKind(rawValue: {KIND})).values.count }}
    fastest = min(fastest, elapsed)
}}
print(found, Double(fastest.components.attoseconds) / 1e12 + Double(fastest.components.seconds) * 1e6)
''')
    # Every size registers under one kind, so the executable links one size per build
    # (BENCHMARK_SIZE); the read counts what it found to confirm which.
    with open(os.path.join(directory, 'Package.swift'), 'w') as file:
        file.write(f'''// swift-tools-version: 6.0
import PackageDescription

let size = Context.environment["BENCHMARK_SIZE"] ?? "{sizes[0]}"

let package = Package(
    name: "Benchmark",
    platforms: [.macOS(.v15)],
    dependencies: [.package(path: "{ROOT}")],
    targets: [
{chr(10).join(targets)}
        .executableTarget(name: "Read", dependencies: [.product(name: "LinkerSets", package: "{PACKAGE}"), .byName(name: "Records" + size)], path: "Sources/Read"),
    ]
)
''')


def timed_build(directory, target, rounds):
    times = []
    for _ in range(rounds):
        # A new modification time makes SwiftPM compile the target again; removing its build
        # products alone doesn't.
        sources = os.path.join(directory, 'Sources', target)
        for name in os.listdir(sources):
            os.utime(os.path.join(sources, name))
        start = time.monotonic()
        swift('build', '--target', target, cwd=directory)
        times.append(time.monotonic() - start)
    return statistics.median(times)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--sizes', default='100,1000,10000')
    parser.add_argument('--rounds', type=int, default=3)
    parser.add_argument('--files', type=int, default=1, help='source files each size is split across')
    options = parser.parse_args()
    sizes = [int(size) for size in options.sizes.split(',')]
    directory = os.path.join(ROOT, '.build', 'benchmark')
    shutil.rmtree(directory, ignore_errors=True)
    os.makedirs(directory)
    write_package(directory, sizes, options.files)
    # Everything the timed targets depend on, built once.
    swift('build', '--target', 'LinkerSets', cwd=directory)

    rows = []
    for size in sizes:
        with_macro = timed_build(directory, f'Records{size}', options.rounds)
        without = timed_build(directory, f'Unrecorded{size}', options.rounds)
        os.environ['BENCHMARK_SIZE'] = str(size)
        swift('build', '-c', 'release', '--product', 'Read', cwd=directory)
        binary = os.path.join(directory, '.build', 'release', 'Read')
        found, microseconds = subprocess.run([binary], capture_output=True, text=True, check=True).stdout.split()
        if int(found) != size:
            sys.exit(f'Read found {found} records of {size}')
        rows.append((size, with_macro, without, (with_macro - without) / size * 1000, float(microseconds)))

    print('| Records | Build with the macro | Build without | Cost per record | Reading every record (release) |')
    print('|---:|---:|---:|---:|---:|')
    for size, with_macro, without, per_record, microseconds in rows:
        print(f'| {size:,} | {with_macro:.1f} s | {without:.1f} s | {per_record:.2f} ms | {microseconds:,.0f} µs |')


if __name__ == '__main__':
    main()
