#!/bin/sh
# Writes Swift sources of many @LinkerSetEntry records, for the scaling tests and the build-time
# benchmark (scripts/benchmark.py).
#
#     many_records.sh <spec>                     one source, to standard output
#     many_records.sh <out>... -- <spec>         the records split evenly across the outputs
#
# The spec holds `<count> <kind>` lines: for each, <count> static properties, each a record of
# <kind>, in an enum per source. A kind of `none` writes the same properties with no macro, the
# build benchmark's control. The compiler takes much longer over thousands of records in one file
# than over the same records spread across several, so the tests' fixture is split.
set -eu

write() { # <spec> <index> <outputs>
    echo "// Generated by tools/many_records from $(basename "$1"); don't edit. \`just sources\` rewrites it."
    if grep -qv ' none$' "$1"; then
        echo "import LinkerSets"
    fi
    while read -r count kind; do
        share=$((count / $3))
        echo
        if [ "$kind" = none ]; then
            echo "enum Unrecorded${count}_$2 {"
        else
            echo "enum Records${count}_$2 {"
        fi
        i=$(($2 * share))
        end=$((i + share))
        while [ "$i" -lt "$end" ]; do
            if [ "$kind" != none ]; then
                echo "    @LinkerSetEntry(kind: $kind)"
            fi
            echo "    static let value$i = $i"
            i=$((i + 1))
        done
        echo "}"
    done < "$1"
}

if [ $# -eq 1 ]; then
    write "$1" 0 1
    exit 0
fi
outputs=""
while [ "$1" != -- ]; do
    outputs="$outputs $1"
    shift
done
spec=$2
total=$(echo $outputs | wc -w | tr -d ' ')
index=0
for output in $outputs; do
    write "$spec" "$index" "$total" > "$output"
    index=$((index + 1))
done
